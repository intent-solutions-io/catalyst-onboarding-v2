#!/usr/bin/env python
"""Render deploy/staging/Caddyfile from the application's own path lists (026 section 8; 6B.8).

The public site serves only the applicant routes (the request form, its received page, and the confirmation,
password and withdrawal links); everything else on the public host is a 404, so the staff screens, the admin and the
health paths never answer there (also refused by config.health.HostGuard). The token segment of every private path
(generated from config.redaction.PRIVATE_PATHS) is redacted in every log line, the error log included, so a link
never lands in a proxy log. Caddy trusts only explicitly configured upstream proxy addresses (loopback by default). The staff site
carries the staff screens and the admin's static files. The Documenso webhook has no site: it is not mounted until
the pilot (P6-D-4).

Run `python scripts/render_caddyfile.py --write` after changing a route; tests/test_staging_proxy.py fails while the
committed file and this rendering differ.
"""

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def _link_paths() -> tuple[str, ...]:
    """CONFIRM_PATH, SETUP_PATH and WITHDRAW_PATH, read from applications/links.py without importing Django, so this
    runs anywhere; tests compare the result with config.redaction.PRIVATE_PATHS."""
    values = {}
    for node in ast.parse((ROOT / "applications" / "links.py").read_text()).body:
        if (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
        ):
            if node.targets[0].id in ("CONFIRM_PATH", "SETUP_PATH", "WITHDRAW_PATH"):
                values[node.targets[0].id] = ast.literal_eval(node.value)
    return tuple(
        values[name] for name in ("CONFIRM_PATH", "SETUP_PATH", "WITHDRAW_PATH")
    )


PRIVATE_PATHS = _link_paths()
# bgl.2 (034 row 1): the first generation's exact paths too, which every link in the wild uses; both forms are routes in v2.
# bgl.8 (034 row 29): the signing return page, where the provider sends a signer (agreements.provider.RETURN_PATH on the
# public base URL) and where the first generation's envelopes already send them; both forms are routes in v2.
PUBLIC_EXACT = (
    "/request-access/",
    "/request-access/received/",
    "/request-access",
    "/request-access/received",
    "/signing/return/",
    "/signing/return",
    "/request-access/assets/select-services-partner-e4897387bbdb.svg",
    "/request-access/assets/select-services-partner-c96bbd4b0d98.png",
)
# bgl.2: what a public host alias (the learning host) is served: the public request pages, nothing else.
ALIAS_PATHS = PUBLIC_EXACT
TARGET = ROOT / "deploy" / "staging" / "Caddyfile"
# 9kg.31.11: the production stack mounts the same file beside its compose definition (the sites take their names from
# the environment, so one rendering serves both).
PRODUCTION_TARGET = ROOT / "deploy" / "production" / "Caddyfile"
LEARN_LOG = ROOT / "deploy" / "cutover" / "catalyst-learn-log.caddy"


for (
    _prefix
) in PRIVATE_PATHS:  # a prefix without its slashes would silently widen what is matched
    if not __import__("re").fullmatch(r"/[a-z0-9-]+/", _prefix):
        raise SystemExit(f"render_caddyfile: unexpected private path {_prefix!r}")


def private_matcher() -> str:
    return " ".join(f"{prefix}*" for prefix in PRIVATE_PATHS)


def _encodable(char: str) -> str:
    """One character as itself or percent-encoded in either case: Caddy's path matcher decodes before matching, but the
    logged URI is the raw request target, so `/%63onfirm/<token>` must be redacted too (PR #69 re-check)."""
    forms = {char, *(f"%{ord(c):02x}" for c in {char.lower(), char.upper()})}
    return "(?:" + "|".join(sorted(forms)) + ")"


def redaction_pattern() -> str:
    """The token segment after any private prefix: any letter case, encoded letters and slashes, repeated slashes."""
    names = "|".join(
        "".join(_encodable(c) for c in prefix.strip("/")) for prefix in PRIVATE_PATHS
    )
    return f"(?i)^/+({names})(?:/|%2f)+[^/?#]+"


def log_format() -> str:
    """The access and error log filter: the token segment of every private path is redacted in the request URI, and
    the Referer header is dropped. With `Referrer-Policy same-origin` (PR #137) a browser sends the token-bearing page
    URL as the Referer of the confirmation POST and of every same-origin asset request, which would land the token in
    the log unredacted (seen in the production proxy log, 2026-10-30)."""
    return f"""format filter {{
			wrap json
			request>uri regexp {redaction_pattern()} /$1/REDACTED
			request>headers>Referer delete
		}}"""


def render() -> str:
    public = " ".join([*PUBLIC_EXACT, *(f"{prefix}*" for prefix in PRIVATE_PATHS)])
    alias = " ".join(ALIAS_PATHS)
    return f"""# Generated by scripts/render_caddyfile.py from the application's path lists (026 section 8; 6B.8).
# Do not edit by hand: change a route, then run `python scripts/render_caddyfile.py --write`.
# A dedicated staging Caddy instance (synthetic data, internal certificates, the web process on its unix socket).
# Never import it into the shared estate Caddyfile: its global options (admin off, the default log) are its own.
{{
	admin off
	# A non-root proxy listens on high ports inside its container (6B.5b review); the host maps 443 to them.
	https_port {{$CATALYST_HTTPS_PORT:443}}
	auto_https disable_redirects
	# Every log line, the error log included, has the token segment of a private path redacted.
	log default {{
		output stderr
		{log_format()}
	}}
	servers {{
		# bgl.20: list only the actual upstream proxy addresses, never all private networks.
		trusted_proxies static {{$CATALYST_TRUSTED_PROXIES:127.0.0.1/32 ::1/128}}
		trusted_proxies_strict
		client_ip_headers X-Forwarded-For
		timeouts {{
			read_header 10s
			read_body 30s
			idle 2m
		}}
	}}
}}

(catalyst_web) {{
	reverse_proxy unix//run/catalyst/web.sock {{
		# Pass one validated client address, after walking only the configured proxy chain.
		header_up X-Forwarded-Proto {{scheme}}
		header_up X-Forwarded-For {{client_ip}}
		header_up -X-Forwarded-Host
		header_down -Server
	}}
}}

(catalyst_site) {{
	log {{
		output stdout
		{log_format()}
	}}
	header {{
		?X-Content-Type-Options nosniff
		?Referrer-Policy same-origin
		-Server
	}}
}}

(catalyst_not_found) {{
	header Cache-Control no-store
	respond 404
}}

{{$CATALYST_PUBLIC_HOST:catalyst.staging.test}} {{
	tls internal
	import catalyst_site
	request_body {{
		max_size 128KB
	}}
	@applicant path {public}
	handle @applicant {{
		import catalyst_web
	}}
	handle {{
		import catalyst_not_found
	}}
}}

# bgl.2: the public host aliases (the learning host's names), for the public request pages only. Never the staff
# screens, the token paths or the health paths. The compose file always gives the proxy a value (a placeholder name
# when no alias is set), so this block always has an address.
{{$CATALYST_PUBLIC_HOST_ALIASES:alias.staging.test}} {{
	tls internal
	import catalyst_site
	request_body {{
		max_size 128KB
	}}
	@alias path {alias}
	handle @alias {{
		import catalyst_web
	}}
	handle {{
		import catalyst_not_found
	}}
}}

{{$CATALYST_STAFF_HOST:staff.staging.test}}:{{$CATALYST_STAFF_PORT:8444}} {{
	bind {{$CATALYST_STAFF_BIND:127.0.0.1}}
	# File-backed TLS is selected only for this named site, never by site order.
	tls {{$CATALYST_STAFF_TLS:internal}}
	import catalyst_site
	request_body {{
		max_size 1MB
	}}
	handle_path /static/* {{
		root * /srv/catalyst/static
		file_server {{
			hide .*
		}}
	}}
	@staff path /staff /staff/*
	handle @staff {{
		import catalyst_web
	}}
	handle {{
		import catalyst_not_found
	}}
}}

# Any other host name on either listener (an unknown name, the staff name on the public port, `localhost`) gets no
# answer at all: Caddy would otherwise reply with an empty 200 (6B.5b staging check). Named sites take precedence.
# The staff port's catch-all binds exactly as the staff site does, so the two share one server: with different binds
# Caddy runs two servers on that port and the kernel spreads connections between them (6B.5b staging check).
:{{$CATALYST_HTTPS_PORT:443}} {{
	tls internal
	abort
}}

:{{$CATALYST_STAFF_PORT:8444}} {{
	bind {{$CATALYST_STAFF_BIND:127.0.0.1}}
	tls internal
	abort
}}
"""


def render_learn_log() -> str:
    """The Learn site's access log for the cutover (026 section 8): R2's token segments redacted, as staging does."""
    return f"""# Generated by scripts/render_caddyfile.py from config.redaction.PRIVATE_PATHS (026 sections 8 and 9).
# The Learn site's access log at the cutover: the token segment of every R2 path is redacted. It replaces the live
# site's own `log` block (a cutover precondition, checked in the live read); the error log needs the same filter.
log {{
	output stdout
	{log_format()}
}}
"""


if __name__ == "__main__":
    if sys.argv[1:] == ["--write"]:
        TARGET.write_text(render())
        PRODUCTION_TARGET.parent.mkdir(exist_ok=True)
        PRODUCTION_TARGET.write_text(render())
        LEARN_LOG.write_text(render_learn_log())
    else:
        sys.stdout.write(render())
