#!/usr/bin/env python
"""Render deploy/staging/Caddyfile from the application's own path lists (026 section 8; 6B.8).

The public site serves only the applicant routes (the request form, its received page, and the confirmation,
password and withdrawal links); everything else on the public host is a 404, so the staff screens, the admin and the
health paths never answer there (also refused by config.health.HostGuard). The token paths are generated from
config.redaction.PRIVATE_PATHS and skipped from every access log, so a link never lands in a proxy log. The staff site
carries the staff screens and the admin's static files. The Documenso webhook has no site: it is not mounted until
the pilot (P6-D-4).

Run `python scripts/render_caddyfile.py --write` after changing a route; tests/test_staging_proxy.py fails while the
committed file and this rendering differ.
"""

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def _link_paths() -> tuple[str, ...]:
    """CONFIRM_PATH, SETUP_PATH and WITHDRAW_PATH, read from applications/links.py without importing Django, so this
    runs anywhere; tests compare the result with config.redaction.PRIVATE_PATHS."""
    values = {}
    for node in ast.parse((ROOT / "applications" / "links.py").read_text()).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if node.targets[0].id in ("CONFIRM_PATH", "SETUP_PATH", "WITHDRAW_PATH"):
                values[node.targets[0].id] = ast.literal_eval(node.value)
    return tuple(values[name] for name in ("CONFIRM_PATH", "SETUP_PATH", "WITHDRAW_PATH"))


PRIVATE_PATHS = _link_paths()
PUBLIC_EXACT = ("/request-access/", "/request-access/received/")
TARGET = ROOT / "deploy" / "staging" / "Caddyfile"


def private_matcher() -> str:
    return " ".join(f"{prefix}*" for prefix in PRIVATE_PATHS)


def render() -> str:
    public = " ".join([*PUBLIC_EXACT, *(f"{prefix}*" for prefix in PRIVATE_PATHS)])
    return f"""# Generated by scripts/render_caddyfile.py from the application's path lists (026 section 8; 6B.8).
# Do not edit by hand: change a route, then run `python scripts/render_caddyfile.py --write`.
# Staging only: synthetic data, internal certificates, the web process on its unix socket.
{{
	admin off
	servers {{
		trusted_proxies static private_ranges
	}}
}}

(catalyst_web) {{
	reverse_proxy unix//run/catalyst/web.sock {{
		# Overwrite, never append: the web process trusts this header for exactly one hop.
		header_up X-Forwarded-Proto {{scheme}}
		header_up -X-Forwarded-Host
		header_up -X-Forwarded-For
	}}
}}

(catalyst_logs) {{
	log {{
		output stdout
		format json
	}}
	# Token paths never reach a log (generated from config.redaction.PRIVATE_PATHS).
	@private_paths path {private_matcher()}
	log_skip @private_paths
}}

{{$CATALYST_PUBLIC_HOST:catalyst.staging.test}} {{
	tls internal
	import catalyst_logs
	request_body {{
		max_size 128KB
	}}
	@applicant path {public}
	handle @applicant {{
		import catalyst_web
	}}
	handle {{
		respond 404
	}}
}}

{{$CATALYST_STAFF_HOST:staff.staging.test}} {{
	bind {{$CATALYST_STAFF_BIND:127.0.0.1}}
	tls internal
	import catalyst_logs
	request_body {{
		max_size 1MB
	}}
	handle_path /static/* {{
		root * /srv/catalyst/static
		file_server
	}}
	@staff path /staff /staff/*
	handle @staff {{
		import catalyst_web
	}}
	handle {{
		respond 404
	}}
}}
"""


if __name__ == "__main__":
    if sys.argv[1:] == ["--write"]:
        TARGET.write_text(render())
    else:
        sys.stdout.write(render())
